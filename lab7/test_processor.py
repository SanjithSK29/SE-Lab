"""Fuzz (property-based) tests for the Cloud Storage Tier processor module.

Each test feeds one of the three functions in ``processor.py`` arbitrary,
unexpected, or malformed inputs generated by Hypothesis and asserts that the
function does not raise any unhandled exception.  When a crash is found,
Hypothesis shrinks the failing input to its smallest counter-example and the
test reports it as a failure so the bug can be fixed.

Run:
    pytest test_processor.py
"""

from hypothesis import given, strategies as st

from processor import (
    parse_storage_quota,
    compute_compression_ratio,
    lookup_bandwidth_tier_rate,
)


@given(st.text() | st.none())
def test_parse_storage_quota_no_crash(s):
    # The function must never crash, no matter what string (or None) it gets.
    try:
        parse_storage_quota(s)
    except Exception as exc:  # noqa: BLE001 - we want to catch every crash
        assert False, f"parse_storage_quota crashed with {s!r}: {exc}"


